class Sense:
    predicate: str
    stems: tuple            # начала форм глагола (после ё→е, нижний регистр)
    prep: str | None = None  # обязательный предлог после глагола
    subject_case: str = "nom"  # nom | dat (нравится)
    inverse: bool = False
    collective: bool = False
    gloss: str = ""          # шаблон пересказа: {0} … {1}
    forms: tuple = ()        # точные формы, если основа не годится
    object_kind: str = "any"  # any | date | number
    preference: bool = False  # при подлежащем «я» → PERSONAL_PREFERENCE

    def matches(self, low: str) -> bool:
        if low in self.forms:
            return True
        if low.endswith(("ся", "сь")):  # возвратные/пассивные формы — только явно перечисленные
            return False
        return any(low.startswith(s) for s in self.stems) and low.endswith(VERB_ENDINGS)


def S(pred, stems, prep=None, gloss="", **kw) -> Sense:
    return Sense(pred, tuple(stems), prep, gloss=gloss, **kw)


