def short_adjective_full_form(low: str) -> str | None:
    """Краткое прилагательное → полная форма для ключа (вреден → вредный, полезна → полезная)."""
    import re as _re
    if low in SHORT_ADJ_STOP or low in GEN_PL_EN or len(low) < 4:
        return None
    if _re.match(r"^[а-я]{2,}[бвгджзклмнпрстфхцчшщ]ен$", low):
        return low[:-2] + "ный"
    if _re.match(r"^[а-я]{2,}[бвгджзклмнпрстфхцчшщ]н[аоы]$", low):
        return low[:-1] + {"а": "ая", "о": "ое", "ы": "ые"}[low[-1]]
    return None


def is_adjective(low: str) -> bool:
    return len(low) > 3 and low.endswith(ADJ_ENDINGS) and not low.endswith(("ство", "ие"))


@dataclass
class Lexicon:
    senses: list = field(default_factory=lambda: list(SENSES))
    comparatives: dict = field(default_factory=lambda: dict(COMPARATIVES))
    glosses: dict = field(default_factory=lambda: dict(GLOSSES))

    def senses_for(self, low: str, next_low: str | None) -> list[Sense]:
        out = []
        for s in self.senses:
            if s.matches(low) and (s.prep is None or s.prep == next_low):
                out.append(s)
        # если есть значения с предлогом и без — предлог задаёт более специфичное прочтение
        with_prep = [s for s in out if s.prep]
        return with_prep if with_prep else out

    @staticmethod
    def load(path: Path | None) -> "Lexicon":
        lex = Lexicon()
        if path is not None and path.exists():
            data = json.loads(path.read_text(encoding="utf-8"))
            for item in data.get("senses", []):
                s = Sense(item["predicate"], tuple(item.get("stems", [])), item.get("prep"),
                          item.get("subject_case", "nom"), bool(item.get("inverse", False)),
                          bool(item.get("collective", False)), item.get("gloss", "{0} " + item["predicate"] + " {1}"),
                          tuple(item.get("forms", [])), item.get("object_kind", "any"),
                          bool(item.get("preference", False)))
                if not re.match(r"^[^\W\d][\w]*$", s.predicate):
                    raise ValueError(f"bad predicate in lexicon: {s.predicate}")
                lex.senses.append(s)
                lex.glosses.setdefault(s.predicate, s.gloss)
        return lex


